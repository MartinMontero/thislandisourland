// Validates i18n/es.json and i18n/ar.json against the English sources and writes the overlays
// dist/js/content.es.js and dist/js/content.ar.js. Also writes i18n/coverage.json and prints
// "N of M" per namespace and language.
//
//   node scripts/build-i18n.mjs            # validate, write overlays, print coverage
//   node scripts/build-i18n.mjs --strict   # also fail when an interface namespace (shell, suggest) is incomplete
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { validate } from './lib/validate-translation.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = (f, d) => (fs.existsSync(path.join(root, f)) ? JSON.parse(fs.readFileSync(path.join(root, f), 'utf8')) : d);
const staticEn = rd('i18n/static.en.json', {});
const stringsEn = rd('i18n/strings.en.json', {});
const NAMESPACES = ['buildpower', 'suggest', 'provenance', 'method', 'wave', 'officials', 'ledger', 'shell'];
const INTERFACE = ['shell', 'suggest'];
const strict = process.argv.includes('--strict');
const LANGS = ['es', 'ar'];
const today = new Date().toISOString().slice(0, 10);

// totals per namespace
const total = Object.fromEntries(NAMESPACES.map((n) => [n, 0]));
Object.values(staticEn).forEach((v) => { total[v.ns] = (total[v.ns] || 0) + 1; });
Object.entries(stringsEn).forEach(([ns, list]) => { total[ns] = (total[ns] || 0) + list.length; });

const coverage = {};
let failed = 0;
for (const lang of LANGS) {
  const src = rd(`i18n/${lang}.json`, { meta: {}, static: {}, strings: {} });
  const done = Object.fromEntries(NAMESPACES.map((n) => [n, 0]));
  const staticOut = {}, stringsOut = {};
  for (const [id, tr] of Object.entries(src.static || {})) {
    const en = staticEn[id];
    if (!en) { console.error(`${lang}: static id not in the English table: ${id}`); failed++; continue; }
    const errs = validate(en.html ?? en.text, tr, lang, { html: en.html !== undefined });
    if (errs.length) { console.error(`${lang} static ${id}: ${errs.join('; ')}`); failed++; continue; }
    staticOut[id] = tr; done[en.ns]++;
  }
  for (const [ns, map] of Object.entries(src.strings || {})) {
    const known = new Set(stringsEn[ns] || []);
    for (const [en, tr] of Object.entries(map)) {
      if (!known.has(en)) { console.error(`${lang}: string not in the English list for ${ns}: ${en.slice(0, 70)}`); failed++; continue; }
      const errs = validate(en, tr, lang);
      if (errs.length) { console.error(`${lang} ${ns} "${en.slice(0, 50)}": ${errs.join('; ')}`); failed++; continue; }
      (stringsOut[ns] ||= {})[en] = tr; done[ns]++;
    }
  }
  coverage[lang] = Object.fromEntries(NAMESPACES.map((n) => [n, { done: done[n], total: total[n] }]));
  const partial = NAMESPACES.some((n) => done[n] < total[n]);
  const overlay = {
    meta: { generated: today, model: (src.meta && src.meta.model) || 'claude-sonnet-5-5 (translated in a Claude Code session)', machine_translated: true, reviewed_by: (src.meta && src.meta.reviewed_by) || null, partial },
    static: staticOut,
    strings: stringsOut
  };
  const js = `/* ${lang}: machine-translated overlay. Generated by scripts/build-i18n.mjs from i18n/${lang}.json. Do not edit. */\n(function (I) {\n  I.content = I.content || {};\n  I.content.${lang} = ${JSON.stringify(overlay)};\n})(window.MOSAIC_I18N);\n`;
  fs.writeFileSync(path.join(root, 'dist', 'js', `content.${lang}.js`), js);
}
fs.writeFileSync(path.join(root, 'i18n', 'coverage.json'), JSON.stringify(coverage, null, 1) + '\n');

for (const lang of LANGS) {
  console.log(`\n${lang}:`);
  for (const n of NAMESPACES) console.log(`  ${n.padEnd(11)} ${coverage[lang][n].done} of ${coverage[lang][n].total} keys translated`);
}
if (strict) for (const lang of LANGS) for (const n of INTERFACE) if (coverage[lang][n].done < coverage[lang][n].total) { console.error(`\n${lang}: interface namespace ${n} is incomplete`); failed++; }
if (failed) { console.error(`\n${failed} problem(s)`); process.exit(1); }
